/**
 * Regenerates apps/api/src/seed-data.ts from fixtures/*.txt. The hosted function can't rely on reading loose files at
 * runtime, so the sample contracts are embedded; a test fails if this file drifts from fixtures/.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const root = join(import.meta.dirname, "..");
const TITLES: Record<string, string> = {
  "mutual-nda": "Mutual NDA - Acme Corp",
  "saas-agreement": "SaaS Agreement - Initech",
  "vendor-msa": "MSA - Hooli",
  "data-processing-addendum": "Data Processing Addendum - Soylent",
  "employment-confidentiality": "Employee Confidentiality Agreement - Stark",
};

const files = readdirSync(join(root, "fixtures")).filter((f) => f.endsWith(".txt")).sort();
const docs = files.map((f) => ({ title: TITLES[basename(f, ".txt")] ?? basename(f, ".txt"), content: readFileSync(join(root, "fixtures", f), "utf8") }));
const out = `// GENERATED by scripts/gen-seed-data.ts from fixtures/*.txt. Do not edit by hand (a test checks it matches).
export interface SeedDocument {
  title: string;
  content: string;
}

export const SEED_DOCUMENTS: SeedDocument[] = ${JSON.stringify(docs, null, 2)};
`;
writeFileSync(join(root, "apps/api/src/seed-data.ts"), out);
console.log(`wrote ${docs.length} documents to apps/api/src/seed-data.ts`);
